HEADER = '''// Vern9: Verner's 9(8) embedded Runge-Kutta pair — the highest-order method
// in this package so far.
//
// GENERATED by tools/emit_vern9_solver.py. There are no numeric literals
// below: every coefficient is a reference to a `Vern9*` const that
// tools/extract_verner.py generated from verner_tableaus.jl (the
// `CompiledFloats` methods, i.e. what Julia's Float64 runtime dispatches to).
//
// Ported from OrdinaryDiffEqVerner:
//   * verner_rk_perform_step.jl:1024 — `perform_step!` on the
//     `Vern9ConstantCache`: k1..k16, `increment_nf!(16)`, the b solution row,
//     the b̃ embedded error, and the k[1..10] store.
//   * verner_addsteps.jl — `_ode_addsteps!`: stages k17..k26, needed only by
//     the interpolant.
//   * interpolants.jl:674/849 — `vern9pre0` (value) and `vern9pre1`
//     (derivative).
//
// Not FSAL (alg_utils.jl `isfsal(::Vern9) = false`): k1 is recomputed as
// `f(uprev, t)` at the top of every step.
//
// Lazy mode (alg.lazy = Val{true}(), the default), matching Vern7:
// `perform_step` evaluates k1..k16 and `fill_dense_stages` computes k17..k26
// on demand through `eval_f_uncounted`, so `sol.nf` reflects 16 evaluations
// per accepted step plus the initial one.
//
// The one thing that makes Vern9 harder to read than Vern7 is the slot
// mapping. `perform_step!` evaluates k1..k16 but stores only
//
//     k[1..10] = k1, k8, k9, k10, k11, k12, k13, k14, k15, k16
//
// dropping k2..k7, which nothing downstream reads. `addsteps!` then puts
// stages k17..k26 into k[11..20]. Every coefficient below is therefore
// addressed by *slot*, not by stage number; `SLOT_OF_STAGE` in the generator
// is the single place that mapping lives.
'''


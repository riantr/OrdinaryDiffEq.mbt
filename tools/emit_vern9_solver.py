# `vern9pre0` / `vern9pre1`: interpolant weight polynomials, as
# (tableau stage, integrator.k slot). Slot 10 (k16) is deliberately absent —
# it only feeds the error estimate.
INTERP_SLOTS = [
    (1, 1), (8, 2), (9, 3), (10, 4), (11, 5), (12, 6), (13, 7), (14, 8),
    (15, 9), (17, 11), (18, 12), (19, 13), (20, 14), (21, 15), (22, 16),
    (23, 17), (24, 18), (25, 19), (26, 20),
]

# Solution row `b` and embedded row `btilde`, as tableau stage -> slot.
B_ROW = [(1, 1), (8, 2), (9, 3), (10, 4), (11, 5), (12, 6), (13, 7),
         (14, 8), (15, 9)]
BTILDE_ROW = B_ROW + [(16, 10)]

W = 20  # integrator.k width, in slots


def slot_index(slot_1based: int) -> int:
    return slot_1based - 1


def coeffs_of(stage: int, ks):
    """`Vern9A<stage><kk>` for each referenced k, in slot order."""
    return [f"Vern9A{stage:02d}{k:02d}" for k in ks]


def sparse_row(stage: int, ks, *, scale_by_dt: bool, width: int = W) -> str:
    """A `width`-wide sparse coefficient array over `integ.k`."""
    cells = ["0.0"] * width
    for k, name in zip(ks, coeffs_of(stage, ks)):
        cells[slot_index(SLOT_OF_STAGE[k])] = f"dt * {name}" if scale_by_dt else name
    lines = []
    for i in range(0, width, 5):
        lines.append("    " + ", ".join(cells[i:i + 5]) + ",")
    return "\n".join(lines)


def row_fn(name: str, doc: str, stage: int, ks, *, index, width: int) -> str:
    """A `width`-wide sparse coefficient array for one tableau stage row."""
    cells = ["0.0"] * width
    for k, cname in zip(ks, coeffs_of(stage, ks)):
        cells[index(k)] = f"dt * {cname}"
    lines = []
    for i in range(0, width, 4):
        lines.append("    " + ", ".join(cells[i:i + 4]) + ",")
    body = "\n".join(lines)
    return (f"///|\n/// {doc}\nfn {name}(dt : Double) -> Array[Double] {{\n"
            f"  [\n{body}\n  ]\n}}\n")


def step_index(k: int) -> int:
    """Position inside `perform_step`'s local stage array (stage - 1)."""
    return k - 1


def slot_zero_index(k: int) -> int:
    """Position inside `integrator.k` (slot - 1), via the slot mapping."""
    return slot_index(SLOT_OF_STAGE[k])


def emit() -> str:
    out = []
    add = out.append

    add(HEADER)

    # --- struct + Solver impl -------------------------------------------
    add(STRUCT)

    # --- perform_step ---------------------------------------------------
    add("// ---------------------------------------------------------------------------\n"
        "// One step\n"
        "// ---------------------------------------------------------------------------\n")
    add(PERFORM_STEP_HEAD)
    for stage, ks in STEP_STAGES:
        # Julia stores no `c` for the two `t + dt` stages (15 and 16): their
        # abscissa is implied, matching `c_field`'s fallback in the extractor.
        abscissa = "dt" if stage in LAST_PAIR else f"Vern9C{stage - 1} * dt"
        add(f"  // k{stage} at t + {abscissa} (row width {len(ks)}).")
        add(f"  lincomb_range(integ.tmp, uprev, vern9_row{stage}(dt), ks)")
        add(f"  Integrator::eval_f(integ, t + {abscissa}, integ.tmp, "
            f"ks.unsafe_get({stage - 1}))")
        add("")
    add(TAIL_PERFORM_STEP)

    # --- lazy extra stages ----------------------------------------------
    add(LAZY_HEADER)
    for stage, ks in LAZY_STAGES:
        add(f"  vern9_extra_stage("
            f"integ, Vern9C{stage}, vern9_extra_row{stage}(dt), "
            f"k.unsafe_get({slot_index(SLOT_OF_STAGE[stage])}))")
    add(LAZY_FOOTER)

    # --- sparse rows ----------------------------------------------------
    add(ROWS_HEADER)
    for stage, ks in STEP_STAGES:
        add(row_fn(
            f"vern9_row{stage}",
            f"Stage {stage} (c = {stage - 1}): "
            + ", ".join(f"k{k}" for k in ks)
            + ". Indexed by tableau stage - 1, i.e. by `perform_step`'s local "
              "stage array; already scaled by `dt`.",
            stage, ks, index=step_index, width=16,
        ))
    add("")
    for stage, ks in LAZY_STAGES:
        add(row_fn(
            f"vern9_extra_row{stage}",
            f"Extra stage {stage}: "
            + ", ".join(f"k{k}" for k in ks)
            + ". Indexed by `integrator.k` slot - 1 (k1 -> slot 1, ..., "
              f"k26 -> slot {W}); already scaled by `dt`.",
            stage, ks, index=slot_zero_index, width=W,
        ))
    add("")

    # --- interpolant ----------------------------------------------------
    add(POLY_SECTION)
    add(INTERP_HEADER)
    n_terms = len(INTERP_SLOTS)
    first_stage, first_slot = INTERP_SLOTS[0]
    add(f"  let th2 = theta * theta")
    add(f"  // k{first_stage} is special: its weight is theta * poly8, not "
        f"theta^2 * poly7.")
    add(f"  let b{first_slot} = theta *")
    add(f"    vern9_poly8(")
    add(f"      theta,")
    for j in range(1, 10):
        add(f"      Vern9R{first_stage:02d}{j},")
    add("    )")
    for stage, slot in INTERP_SLOTS[1:]:
        add(f"  let b{slot} = th2 *")
        add(f"    vern9_poly7(")
        add(f"      theta,")
        for j in range(2, 10):
            add(f"      Vern9R{stage:02d}{j},")
        add("    )")
    add(f"  let n = out.length()")
    add("  let mut i = 0")
    add("  while i < n {")
    add("    out.unsafe_set(")
    add("      i,")
    add("      y0.unsafe_get(i) +")
    add("      dt *")
    add("      (")
    for idx, (stage, slot) in enumerate(INTERP_SLOTS):
        tail = "" if idx == len(INTERP_SLOTS) - 1 else " +"
        add(f"        ks.unsafe_get({slot_index(slot)}).unsafe_get(i) * b{slot}{tail}")
    add("      ),")
    add("    )")
    add("    i += 1")
    add("  }")
    add("}")
    add("")

    add(INTERP_DERIV_HEADER)
    add(f"  let b{first_slot} =")
    add(f"    vern9_poly8_x_d(")
    add(f"      theta,")
    for j in range(1, 10):
        add(f"      Vern9R{first_stage:02d}{j},")
    add("    )")
    for stage, slot in INTERP_SLOTS[1:]:
        add(f"  let b{slot} =")
        add(f"    vern9_poly7_x2_d(")
        add(f"      theta,")
        for j in range(2, 10):
            add(f"      Vern9R{stage:02d}{j},")
        add("    )")
    add("  let n = out.length()")
    add("  let mut i = 0")
    add("  while i < n {")
    add("    out.unsafe_set(")
    add("      i,")
    for idx, (stage, slot) in enumerate(INTERP_SLOTS):
        tail = "," if idx == len(INTERP_SLOTS) - 1 else " +"
        add(f"      ks.unsafe_get({slot_index(slot)}).unsafe_get(i) * b{slot}{tail}")
    add("    )")
    add("    i += 1")
    add("  }")
    add("}")
    add("")

    # --- invariants -----------------------------------------------------
    add(emit_invariants())
    return "\n".join(out)



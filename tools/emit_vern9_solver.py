"""Generate src/src/alg_vern9.mbt — the Vern9 solver body.

Vern7 was written by hand; Vern9 is too repetitive to transcribe by hand
(16 step stages, 10 lazy stages, 20 interpolant terms), so the boilerplate
here is emitted instead. There are still **no numeric literals** in the
output: every coefficient is a reference to a `Vern9*` const generated by
tools/extract_verner.py from verner_tableaus.jl.

The three facts this file encodes, all read off OrdinaryDiffEqVerner:

1. `perform_step!` (verner_rk_perform_step.jl:1024) evaluates k1..k16 with
   `increment_nf!(16)`; `integrator.k[1..10]` then hold
   k1, k8, k9, k10, k11, k12, k13, k14, k15, k16 — k2..k7 are dropped
   because nothing downstream reads them.
2. `_ode_addsteps!` fills `integrator.k[11..20]` with stages 17..26, whose
   rows reference k1, k8..k15 and k17..k21 (note k16 is *not* referenced).
3. `vern9pre0` (interpolants.jl:674) reads k[1], k[2..9] and k[11..20];
   k[10] (= k16) is used only by the embedded error estimate.
"""

